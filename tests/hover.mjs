import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] })
const p = await b.newPage({ viewport: { width: 1440, height: 900 } })
const errs=[]; p.on('pageerror',e=>errs.push(e.message))
await p.goto('http://127.0.0.1:5173/?intro=0'); await p.waitForTimeout(3000)
const y = await p.evaluate(()=>{const s=[...document.querySelectorAll('div')].find(d=>d.style.height==='320vh'); return s.offsetHeight - innerHeight})
await p.evaluate(v=>window.scrollTo({top:v*0.7,behavior:'instant'}),y); await p.waitForTimeout(800)
await p.evaluate(v=>window.scrollTo({top:v,behavior:'instant'}),y); await p.waitForTimeout(9000)
await p.screenshot({path:'shots/h0.png'})
const box = await p.locator('[role=button][aria-label^="Ouvrir"]').nth(3).boundingBox()
await p.mouse.move(box.x+box.width*0.6, box.y+box.height*0.5); await p.waitForTimeout(1500)
await p.screenshot({path:'shots/h1.png'})
console.log('errs',errs)
await b.close()
