import { chromium } from 'playwright'
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-gl=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] })
const p = await b.newPage({ viewport: { width: 1100, height: 650 } })
const errs=[]; p.on('pageerror',e=>errs.push(e.message)); p.on('console',m=>m.type()==='error'&&errs.push(m.text()))
await p.goto('http://127.0.0.1:5173/?intro=0'); await p.waitForTimeout(3000)
const y = await p.evaluate(()=>{const s=document.querySelector('[data-stage]'); return s.offsetHeight - innerHeight})
await p.evaluate(v=>window.scrollTo({top:v,behavior:'instant'}),y); await p.waitForTimeout(5000)
const before = await p.evaluate(()=>Math.round(scrollY))
await p.locator('[role=button][aria-label^="Ouvrir Aur"]').first().focus()
await p.keyboard.press('Enter')
await p.waitForTimeout(6000)
console.log('hash', await p.evaluate(()=>location.hash), 'scroll in demo', await p.evaluate(()=>Math.round(scrollY)))
await p.waitForTimeout(500)
await p.screenshot({path:'shots/rt-demo.png'})
await p.locator('a:has-text("OFF/SCRIPT"):visible').first().click()
for (const [i,ms] of [[0,350],[1,500],[2,500],[3,900],[4,3000]]) { await p.waitForTimeout(ms); await p.screenshot({path:`shots/rt${i}.png`}) }
const after = await p.evaluate(()=>Math.round(scrollY))
console.log('before',before,'after',after,'hash',await p.evaluate(()=>location.hash),'errs',errs.slice(0,4))
// open again to prove windows still work
await p.locator('[role=button][aria-label^="Ouvrir "]').nth(4).focus(); await p.keyboard.press('Enter'); await p.waitForTimeout(6000)
console.log('second open hash', await p.evaluate(()=>location.hash))
await b.close()
